'use strict';
var assert = require('assert');
var stream = require('../app/aerial-stream');
assert.deepStrictEqual(stream.rangeFor('bytes=0-19',100),{start:0,end:19,partial:true});
assert.deepStrictEqual(stream.rangeFor('bytes=50-',100),{start:50,end:99,partial:true});
assert.deepStrictEqual(stream.rangeFor('bytes=-20',100),{start:80,end:99,partial:true});
assert.deepStrictEqual(stream.rangeFor(null,100),{start:0,end:99,partial:false});
assert.strictEqual(stream.rangeFor('bytes=100-',100),null);
assert.strictEqual(stream.rangeFor('bytes=5-3',100),null);
assert.strictEqual(stream.rangeFor('bytes=0-1,4-6',100),null);
var original=Buffer.alloc(128,97); original.write('ftyp',4); original.write('qt  ',8); original.write('qt  ',16);
var changed=stream.normalizeBrands(Buffer.from(original),0);
assert.strictEqual(changed.toString('ascii',8,12),'isom');
assert.strictEqual(changed.toString('ascii',16,20),'isom');
assert.deepStrictEqual(changed.slice(20),original.slice(20),'Encoded video payload is unchanged');
assert.strictEqual(changed.length,original.length,'Byte-range offsets remain valid');
var chunk=Buffer.from('qt  '); stream.normalizeBrands(chunk,16); assert.strictEqual(chunk.toString(),'isom');
var media=Buffer.from('qt  payload'); assert.strictEqual(stream.normalizeBrands(media,100).toString(),'qt  payload');
console.log('Aerial transport: passed (full/open/suffix ranges, invalid ranges, container brands, partial headers, unchanged payload and length)');
