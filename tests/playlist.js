var assert = require('assert');
var fs = require('fs');
var parse = require('../app/iptv');
var channels = parse(fs.readFileSync('app/channels.m3u', 'utf8'));
assert.strictEqual(channels.length, 15);
assert.strictEqual(channels[1].name, 'Belarus-1 (1080p)');
assert.ok(channels.every(function (item) { return /^https?:\/\//.test(item.url); }));
var tricky = '\uFEFF#EXTM3U\r\n#EXTINF:-1 group-title="News, local",Channel, one\r\n#EXTVLCOPT:ignored\r\nhttps://example.org/live.m3u8\r\n#EXTINF:-1,Duplicate\nhttps://example.org/live.m3u8\n#EXTINF:-1,Unsafe\njavascript:alert(1)\n#EXTINF:-1,No URL';
var parsed = parse(tricky);
assert.strictEqual(parsed.length, 1);
assert.strictEqual(parsed[0].name, 'Channel, one');
assert.strictEqual(parsed[0].group, 'News, local');
assert.deepStrictEqual(parse('garbage\nhttps://example.org'), []);
console.log('Playlist parser: passed (snapshot, CRLF/BOM, attributes, duplicates, unsafe URLs, incomplete entries)');
var hd = parse.hdChannels(channels);
assert.strictEqual(hd.length, 11);
assert.ok(hd.every(function (channel) { return channel.height >= 720; }));
assert.ok(hd.some(function (channel) { return channel.height === 720; }));
assert.ok(!hd.some(function (channel) { return channel.name.indexOf('(576p)') !== -1; }));
assert.strictEqual(hd[0].id, 'Belarus1.by@SD');
assert.strictEqual(hd[0].logo, 'https://i.imgur.com/sUD9t5j.png');
assert.strictEqual(parse.hdChannels(parse('#EXTINF:-1 tvg-logo="javascript:bad",Unknown HD\nhttps://example.org/live\n')).length, 0);
assert.strictEqual(parse('#EXTINF:-1 tvg-logo="javascript:bad",Safe (720p)\nhttps://example.org/live\n')[0].logo, '');
console.log('HD filter and logo metadata: passed (720p boundary, 576p exclusion, unknown quality, safe URL)');
