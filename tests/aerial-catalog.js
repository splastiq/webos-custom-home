'use strict';
var assert = require('assert');
var catalog = require('../app/aerial-catalog');
var createStorage = require('../app/storage');
var storageData = {};
var store = createStorage({ getItem: function (key) { return storageData[key] || null; }, setItem: function (key, value) { storageData[key] = value; } });
var asset = { id: 'one', accessibilityLabel: 'Dubai', 'url-4K-SDR': 'https://sylvan.apple.com/a4k.mov', 'url-1080-SDR': 'https://sylvan.apple.com/a1080.mov', 'url-1080-H264': 'https://sylvan.apple.com/ah264.mov' };
var normalized = catalog.normalize({ assets: [asset, asset, { id: 'bad', 'url-4K-SDR': 'https://sylvan.apple.com.evil.test/file.mov' }, { id: 'credentials', 'url-4K-SDR': 'https://user@sylvan.apple.com/file.mov' }, { id: 'js', 'url-1080-H264': 'javascript:alert(1)' }, null] });
assert.strictEqual(normalized.length, 1);
assert.strictEqual(normalized[0].label, 'Дубай');
assert.deepStrictEqual(catalog.variants(normalized[0], true), [asset['url-4K-SDR'], asset['url-1080-SDR'], asset['url-1080-H264']]);
assert.deepStrictEqual(catalog.variants(normalized[0], false), [asset['url-1080-H264']]);
assert.deepStrictEqual(catalog.normalize({ assets: [{ id: 'hdr-only', 'url-4K-HDR': 'https://sylvan.apple.com/hdr.mov' }] }), [], 'Do not silently select HDR');
var requests = [];
function XHR() { requests.push(this); }
XHR.prototype.open = function () {};
XHR.prototype.send = function () {};
XHR.prototype.abort = function () { this.aborted = true; };
var source = catalog.create({ bundled: { assets: [asset] }, storage: store, XMLHttpRequest: XHR });
var now = 1780000000000;
source.refresh(now, false); assert.strictEqual(requests.length, 0);
source.refresh(now, true); assert.strictEqual(requests.length, 1);
requests[0].onerror(); assert.strictEqual(source.assets().length, 1, 'CORS failure keeps bundled assets');
source.refresh(now + 1000, true); assert.strictEqual(requests.length, 1, 'Failures are throttled');
source.refresh(now + 3600000, true);
var second = Object.assign({}, asset, { id: 'two' });
requests[1].status = 200; requests[1].responseText = JSON.stringify({ assets: [second] }); requests[1].onload();
assert.strictEqual(source.assets().length, 2);
var restored = catalog.create({ bundled: { assets: [asset] }, storage: store, XMLHttpRequest: XHR });
assert.strictEqual(restored.assets().length, 2, 'Only metadata survives restart');
restored.refresh(now + 3601000, true); assert.strictEqual(requests.length, 2, 'Fresh catalog is not downloaded again');
restored.refresh(now + 9 * 86400000, true); restored.cancel();
assert.strictEqual(requests[2].aborted, true);
assert.strictEqual(source.assets()[0].id, 'one', 'Bundled compatible fallback is kept first');
console.log('Aerial catalog: passed (Apple-only URLs, SDR variants, H.264 fallback, invalid input, offline, CORS, throttling, metadata cache, cancellation)');
var local = Object.assign({}, asset, { previewLocal: 'aerial-thumbs/one.jpg' });
assert.strictEqual(catalog.normalize({ assets: [local] })[0].preview, 'aerial-thumbs/one.jpg');
local.previewLocal = 'aerial-thumbs/../../secret.jpg';
assert.strictEqual(catalog.normalize({ assets: [local] })[0].preview, '', 'Thumbnail paths cannot escape the packaged directory');
var rich = Object.assign({}, asset, { timeOfDay: 'night', scene: 'space', pointsOfInterest: { '10': 'POINT_KEY' }, 'url-4K-HDR': 'https://sylvan.apple.com/hdr.mov' });
var detailed = catalog.normalize({ assets: [rich] })[0];
assert.deepStrictEqual(detailed.metadata, rich, 'Original JSON fields remain available for details without affecting playback sources');
